//! xtgeoip-tests — SYSTEM INTEGRATION test suite (not unit tests).
//!
//! This is **not** `cargo test`. It drives the real `xtgeoip` binary against
//! the real filesystem as root, and it is stateful. Understand these
//! properties before using or modifying it (#87):
//!
//! - **Requires root.** Every case is spawned via `sudo`.
//! - **Cases write to a sandbox, not to production (#98).** Each run creates a
//!   private temp tree, seeds it from the configured `output_dir` and
//!   `archive_dir`, and spawns every case with `--config <sandbox>` so all
//!   writes land there. Production data is read once to seed, never written.
//!   The sandbox is removed on the way out unless `--keep-sandbox` is given.
//! - **Requires a real release build.** Cases execute `target/release/xtgeoip`
//!   by default — not a debug build, not a Cargo test harness. Run `cargo build
//!   --release` first, or point `--bin` elsewhere.
//! - **Order-dependent, and cases depend on prior execution.** Cases run in
//!   file order and mutate sandbox state that later cases observe. `TL-007`
//!   (`xtgeoip -c`) empties `output_dir`, so every case after it runs against a
//!   cleaned tree. The corpus order is pinned by `emission_order_is_stable`; do
//!   not reorder it (see #77). The first case needing a populated `output_dir`
//!   is `TL-006`, and nothing before it builds one — which is why the sandbox
//!   is seeded rather than started empty.
//! - **`--rebuild` is effectively required for a full run.** Without it, cases
//!   marked `rebuild: true` leave `output_dir` empty and later top-level `-b`
//!   cases fail with "Nothing to back up" — *false* failures that look like
//!   regressions. Omitting it has already cost one debugging session.
//! - **It no longer reaches MaxMind (#98).** A local HTTPS stub (`openssl
//!   s_server`) serves the two endpoints `fetch` uses, replaying the newest
//!   seeded archive under a synthetic version. Each case is given the stub's CA
//!   via `--ca-file`, which *replaces* its trust roots, so a case that somehow
//!   addressed the real API would fail to verify it rather than quietly
//!   succeed. The run fails if the stub is never reached.
//! - **It still prompts for the credentials passphrase**, once per remote case.
//!   `secrets::decrypt` reads from the terminal by design (#103) and the runner
//!   deliberately does not route around it. The stub removes the WAN traffic
//!   and the rate cap, not the prompts.
//! - **Run from the repository root**, which is where the default binary path
//!   and `docs/generated/testcases.yaml` resolve from.
//!
//! Cases come from `docs/generated/testcases.yaml`, generated by
//! `xtgeoip-docgen` from `docs/spec/cli.yaml`. Each asserts the exit status
//! its spec key implies:
//!   key: p  → must exit 0
//!   key: f  → must exit non-zero
//!
//! Optional output assertions:
//!   expected_stdout: ""        → stdout must be empty
//!   expected_stdout: "text"    → stdout must contain "text"
//!   expected_stderr: (same)
//!
//! The `#[cfg(test)]` module at the bottom *is* root-free and runs under
//! `cargo test`; it covers corpus parsing, schema versioning and binary-path
//! resolution — not the cases themselves.
//!
//! Run `xtgeoip-tests --help` for flags.

